// Package gateway turns a SiteRouter into the objects of its gateway: the VM,
// its boot disk, the Secrets, the Service of the tunnel and, when the platform
// asks for them, the network policies.
//
// Render is a pure function. It reads no cluster, clock or random source, so
// what a SiteRouter becomes can be tested without a cluster and the same input
// always gives the same objects. Whatever must be generated once and then kept,
// such as the pre-shared key, is generated by the caller and passed in. Applying
// the objects, and keeping what must not be overwritten, is not done here.
package gateway

import (
	"errors"
	"fmt"
	"maps"
	"regexp"
	"slices"
	"strings"

	corev1 "k8s.io/api/core/v1"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/apis/meta/v1/unstructured"
	"k8s.io/apimachinery/pkg/runtime"
	"k8s.io/apimachinery/pkg/runtime/schema"
	"k8s.io/apimachinery/pkg/util/intstr"
	"sigs.k8s.io/controller-runtime/pkg/client"

	"github.com/aenix-io/site-router-operator/api/engine"
	"github.com/aenix-io/site-router-operator/api/v1alpha1"
)

// Kinds of the objects that have no Go type here. They are built as
// unstructured objects, so that the operator carries no dependency on KubeVirt,
// CDI or Cilium and does not break when one of them moves a field it does not
// use.
var (
	VirtualMachineGVK      = schema.GroupVersionKind{Group: "kubevirt.io", Version: "v1", Kind: "VirtualMachine"}
	DataVolumeGVK          = schema.GroupVersionKind{Group: "cdi.kubevirt.io", Version: "v1beta1", Kind: "DataVolume"}
	CiliumNetworkPolicyGVK = schema.GroupVersionKind{Group: "cilium.io", Version: "v2", Kind: "CiliumNetworkPolicy"}
)

// Ports of the tunnel.
const (
	portIKE  = 500
	portNATT = 4500
)

// linkLocal is always denied to the gateway: it holds the metadata endpoint of
// a cloud.
const linkLocal = "169.254.0.0/16"

// What recurs in the objects, which are built as maps.
const (
	fieldName   = "name"
	fieldSpec   = "spec"
	networkName = "default" // of the one network and the one interface of the VM
)

// ErrIsolationUnavailable is returned by Render when the configuration has the
// gateway run with no isolation and does not acknowledge it. A gateway is not
// created in that case.
var ErrIsolationUnavailable = errors.New("gateway isolation is not available")

// Input is everything a gateway is made of.
type Input struct {
	Instance *v1alpha1.SiteRouter
	Config   Config
	// Image is the appliance disk for the version in use, pinned by digest. It
	// comes from the operator's configuration, not from the engine.
	Image string
	Plan  engine.BootstrapPlan
	// PSK goes into the Secret the operator creates when the SiteRouter names
	// none. It is not used when the SiteRouter does.
	PSK []byte
}

// OwnsPSKSecret reports whether the operator creates the Secret with the
// pre-shared key of the SiteRouter, which it does when none is named.
func OwnsPSKSecret(sr *v1alpha1.SiteRouter) bool {
	return sr.Spec.Peer.Auth == nil || sr.Spec.Peer.Auth.SecretRef == nil
}

// Render returns the objects of the gateway, in the order they are created: the
// Secrets and the disk first, then the VM that uses them, then what reaches it.
// An object that breaks an invariant of the gateway is never returned.
func Render(in Input) ([]client.Object, error) {
	if err := in.check(); err != nil {
		return nil, err
	}
	r := renderer{in: in, names: NamesFor(in.Instance.Name).ForImage(in.Image)}

	url, err := registryURL(in.Image)
	if err != nil {
		return nil, err
	}
	vm, err := r.virtualMachine()
	if err != nil {
		return nil, err
	}

	objs := []client.Object{r.apiKeySecret(), r.cloudInitSecret()}
	if OwnsPSKSecret(in.Instance) {
		objs = append(objs, r.pskSecret())
	}
	objs = append(objs, r.dataVolume(url), vm, r.tunnelService())
	if in.Config.Isolation.Mode == IsolationCilium {
		objs = append(objs, r.egressDenyPolicy(), r.ingressPolicy())
	}

	if err := assertInvariants(in, objs); err != nil {
		return nil, fmt.Errorf("the rendered gateway breaks an invariant: %w", err)
	}
	return objs, nil
}

func (in Input) check() error {
	sr := in.Instance
	if sr == nil {
		return errors.New("no SiteRouter to render")
	}
	var errs []error
	add := func(format string, args ...any) { errs = append(errs, fmt.Errorf(format, args...)) }

	if sr.Name == "" || sr.Namespace == "" {
		add("the SiteRouter has no name or namespace")
	}
	if sr.UID == "" {
		add("the SiteRouter has no UID: what is created for it cannot be owned by it")
	}
	if sr.Spec.Resources.CPU < 1 || sr.Spec.Resources.Memory.IsZero() {
		add("the resources of the SiteRouter are not set: the API server fills in the defaults, so this object did not come from it")
	}

	p := in.Plan
	if p.Arch == "" {
		add("the plan of the engine names no architecture")
	}
	if p.DiskGiB <= 0 {
		add("the plan of the engine has no disk size")
	}
	if p.ManagementPort <= 0 || p.ManagementPort > 65535 {
		add("the plan of the engine has no management port")
	}
	if len(p.SeedFiles[engine.SeedUserData]) == 0 {
		add("the plan of the engine has no seed file %q, which is the one the guest reads", engine.SeedUserData)
	}
	if len(p.Credentials) == 0 {
		add("the plan of the engine has no credentials")
	}
	if OwnsPSKSecret(sr) && len(in.PSK) == 0 {
		add("the SiteRouter names no Secret for the pre-shared key and none was generated")
	}
	if _, err := registryURL(in.Image); err != nil {
		errs = append(errs, err)
	}
	if err := in.Config.Validate(); err != nil {
		errs = append(errs, err)
	}
	if len(errs) > 0 {
		return errors.Join(errs...)
	}
	if in.Config.Isolation.Mode == IsolationNone && !in.Config.Isolation.AcknowledgeNone {
		return fmt.Errorf("%w: isolation.mode is none and isolation.acknowledgeNone is not set", ErrIsolationUnavailable)
	}
	return nil
}

// CheckImage says whether image is a reference the gateway can be made from: one
// pinned by a digest.
func CheckImage(image string) error {
	_, err := registryURL(image)
	return err
}

var (
	digestRE = regexp.MustCompile(`^sha256:[0-9a-f]{64}$`)
	tagRE    = regexp.MustCompile(`:[^:/]+$`)
)

// registryURL turns an image reference pinned by digest into the source URL of
// a DataVolume. The tag is dropped, because the importer cannot parse a
// reference that carries both a tag and a digest, and the digest is what pins
// the image anyway. A reference with no digest is refused: the importer would
// take the tag and the disk could change under the same name.
func registryURL(image string) (string, error) {
	repo, digest, ok := strings.Cut(image, "@")
	if !ok || !digestRE.MatchString(digest) {
		return "", fmt.Errorf("the image %q is not pinned by a digest (<repository>[:<tag>]@sha256:<64 hex digits>)", image)
	}
	repo = tagRE.ReplaceAllString(repo, "")
	if repo == "" || strings.ContainsAny(repo, " \t\n") || strings.Contains(repo, "://") {
		return "", fmt.Errorf("the image %q has no repository the importer can use", image)
	}
	return "docker://" + repo + "@" + digest, nil
}

type renderer struct {
	in    Input
	names Names
}

func (r renderer) labels() map[string]string { return Labels(r.in.Instance.Name) }

func (r renderer) owner() metav1.OwnerReference { return OwnerReference(r.in.Instance) }

func (r renderer) meta(name string) metav1.ObjectMeta {
	return metav1.ObjectMeta{
		Name:            name,
		Namespace:       r.in.Instance.Namespace,
		Labels:          r.labels(),
		OwnerReferences: []metav1.OwnerReference{r.owner()},
	}
}

func (r renderer) unstructured(gvk schema.GroupVersionKind, name string, spec map[string]any) *unstructured.Unstructured {
	u := &unstructured.Unstructured{Object: map[string]any{fieldSpec: spec}}
	u.SetGroupVersionKind(gvk)
	u.SetName(name)
	u.SetNamespace(r.in.Instance.Namespace)
	u.SetLabels(r.labels())
	u.SetOwnerReferences([]metav1.OwnerReference{r.owner()})
	return u
}

func (r renderer) secret(name string, data map[string][]byte) *corev1.Secret {
	return &corev1.Secret{
		APIVersion: "v1",
		Kind:       "Secret",
		ObjectMeta: r.meta(name),
		Type:       corev1.SecretTypeOpaque,
		Data:       cloneData(data),
	}
}

// forImage marks an object as made for the image of the gateway.
func (r renderer) forImage(o interface {
	GetAnnotations() map[string]string
	SetAnnotations(map[string]string)
}) {
	a := o.GetAnnotations()
	if a == nil {
		a = map[string]string{}
	}
	a[v1alpha1.AnnotationImageDigest], _ = ImageDigest(r.in.Image)
	o.SetAnnotations(a)
}

func (r renderer) apiKeySecret() *corev1.Secret {
	return r.secret(r.names.APIKey, r.in.Plan.Credentials)
}

func (r renderer) cloudInitSecret() *corev1.Secret {
	s := r.secret(r.names.CloudInit, r.in.Plan.SeedFiles)
	r.forImage(s)
	return s
}

func (r renderer) pskSecret() *corev1.Secret {
	return r.secret(r.names.PSK, map[string][]byte{"psk": r.in.PSK})
}

func cloneData(m map[string][]byte) map[string][]byte {
	out := make(map[string][]byte, len(m))
	for k, v := range m {
		out[k] = slices.Clone(v)
	}
	return out
}

func (r renderer) dataVolume(url string) *unstructured.Unstructured {
	dv := r.in.Config.DataVolume
	registry := map[string]any{"url": url}
	if dv.Source.PullMethod != "" {
		registry["pullMethod"] = dv.Source.PullMethod
	}
	if dv.Source.CertConfigMap != "" {
		registry["certConfigMap"] = dv.Source.CertConfigMap
	}
	if dv.Source.SecretRef != "" {
		registry["secretRef"] = dv.Source.SecretRef
	}
	storage := map[string]any{
		"resources": map[string]any{"requests": map[string]any{"storage": fmt.Sprintf("%dGi", r.in.Plan.DiskGiB)}},
	}
	// Left out when empty, never set to "": an empty class name asks for a volume
	// that was provisioned beforehand, where absent asks for the default class.
	if class := r.storageClass(); class != "" {
		storage["storageClassName"] = class
	}
	disk := r.unstructured(DataVolumeGVK, r.names.BootDisk, map[string]any{
		"contentType": "kubevirt",
		"source":      map[string]any{"registry": registry},
		"storage":     storage,
	})
	r.forImage(disk)
	return disk
}

// storageClass is the one the SiteRouter asks for, else the one of the platform.
func (r renderer) storageClass() string {
	if sc := r.in.Instance.Spec.StorageClass; sc != "" {
		return sc
	}
	return r.in.Config.DataVolume.StorageClass
}

func (r renderer) virtualMachine() (*unstructured.Unstructured, error) {
	sr, cfg := r.in.Instance, r.in.Config

	annotations := anyMap(cfg.VM.PodAnnotations)
	annotations["kubevirt.io/allow-pod-bridge-network-live-migration"] = "true"

	labels := anyMap(cfg.VM.PodLabels)
	for k, v := range r.labels() {
		labels[k] = v
	}

	nodeSelector := anyMap(cfg.VM.NodeSelector)
	nodeSelector["kubernetes.io/arch"] = r.in.Plan.Arch

	pod := map[string]any{
		"domain": map[string]any{
			"cpu":      map[string]any{"cores": int64(sr.Spec.Resources.CPU), "sockets": int64(1), "threads": int64(1)},
			"memory":   map[string]any{"guest": sr.Spec.Resources.Memory.String()},
			"firmware": map[string]any{"uuid": string(sr.UID)},
			"devices": map[string]any{
				"disks": []any{
					map[string]any{
						fieldName:   "boot",
						"disk":      map[string]any{"bus": "virtio"},
						"bootOrder": int64(1),
						"blockSize": map[string]any{"custom": map[string]any{
							"logical":  int64(cfg.DataVolume.BlockSize.Logical),
							"physical": int64(cfg.DataVolume.BlockSize.Physical),
						}},
					},
					map[string]any{fieldName: "cloudinitdisk", "disk": map[string]any{}},
				},
				"interfaces": []any{map[string]any{fieldName: networkName, "bridge": map[string]any{}}},
			},
			"machine": map[string]any{"type": ""},
		},
		"nodeSelector":                  nodeSelector,
		"terminationGracePeriodSeconds": int64(30),
		"volumes": []any{
			map[string]any{fieldName: "boot", "dataVolume": map[string]any{fieldName: r.names.BootDisk}},
			map[string]any{fieldName: "cloudinitdisk", "cloudInitNoCloud": map[string]any{"secretRef": map[string]any{fieldName: r.names.CloudInit}}},
		},
		"networks": []any{map[string]any{fieldName: networkName, "pod": map[string]any{}}},
	}
	if len(cfg.VM.Tolerations) > 0 {
		tolerations := make([]any, 0, len(cfg.VM.Tolerations))
		for _, t := range cfg.VM.Tolerations {
			m, err := runtime.DefaultUnstructuredConverter.ToUnstructured(&t)
			if err != nil {
				return nil, fmt.Errorf("converting a toleration: %w", err)
			}
			tolerations = append(tolerations, m)
		}
		pod["tolerations"] = tolerations
	}
	if cfg.VM.Affinity != nil {
		m, err := runtime.DefaultUnstructuredConverter.ToUnstructured(cfg.VM.Affinity)
		if err != nil {
			return nil, fmt.Errorf("converting the affinity: %w", err)
		}
		pod["affinity"] = m
	}
	if cfg.VM.PriorityClassName != "" {
		pod["priorityClassName"] = cfg.VM.PriorityClassName
	}
	if cfg.VM.RuntimeClassName != "" {
		pod["runtimeClassName"] = cfg.VM.RuntimeClassName
	}

	return r.unstructured(VirtualMachineGVK, r.names.VM, map[string]any{
		"runStrategy": "Always",
		"template": map[string]any{
			"metadata": map[string]any{"annotations": annotations, "labels": labels},
			fieldSpec:  pod,
		},
	}), nil
}

func (r renderer) tunnelService() *corev1.Service {
	cfg := r.in.Config.Service
	meta := r.meta(r.names.Tunnel)
	if len(cfg.Annotations) > 0 {
		meta.Annotations = maps.Clone(cfg.Annotations)
	}
	svc := &corev1.Service{
		APIVersion: "v1",
		Kind:       "Service",
		ObjectMeta: meta,
		Spec: corev1.ServiceSpec{
			Type: corev1.ServiceTypeLoadBalancer,
			// Local keeps the address of the remote end, which the gateway needs
			// to match the peer.
			ExternalTrafficPolicy: corev1.ServiceExternalTrafficPolicyLocal,
			Ports: []corev1.ServicePort{
				{Name: "isakmp", Protocol: corev1.ProtocolUDP, Port: portIKE, TargetPort: intstr.FromInt32(portIKE)},
				{Name: "ipsec-nat-t", Protocol: corev1.ProtocolUDP, Port: portNATT, TargetPort: intstr.FromInt32(portNATT)},
			},
			Selector: map[string]string{v1alpha1.LabelInstance: r.in.Instance.Name},
		},
	}
	if cfg.LoadBalancerClass != "" {
		svc.Spec.LoadBalancerClass = &cfg.LoadBalancerClass
	}
	return svc
}

func (r renderer) endpointSelector() map[string]any {
	return map[string]any{"matchLabels": map[string]any{v1alpha1.LabelInstance: r.in.Instance.Name}}
}

// egressDenyPolicy keeps the gateway from reaching what a tenant must not reach
// through it. A deny rule of Cilium wins over every allow rule, so this holds
// whatever else the namespace allows.
func (r renderer) egressDenyPolicy() *unstructured.Unstructured {
	cidrs := []any{linkLocal}
	extra := slices.Compact(slices.Sorted(slices.Values(r.in.Config.Isolation.EgressDenyCIDRs)))
	for _, c := range extra {
		if c != linkLocal {
			cidrs = append(cidrs, c)
		}
	}
	return r.unstructured(CiliumNetworkPolicyGVK, r.names.EgressDeny, map[string]any{
		"endpointSelector": r.endpointSelector(),
		"egressDeny":       []any{map[string]any{"toCIDR": cidrs}},
	})
}

// ingressPolicy admits to the gateway the tunnel from the world and the
// management API for the operator, and nothing else.
func (r renderer) ingressPolicy() *unstructured.Unstructured {
	ctl := r.in.Config.Isolation.Controller
	from := map[string]any{"k8s:io.kubernetes.pod.namespace": ctl.Namespace}
	for k, v := range ctl.Labels {
		from["k8s:"+k] = v
	}
	port := func(p int, proto string) any {
		return map[string]any{"port": fmt.Sprint(p), "protocol": proto}
	}
	return r.unstructured(CiliumNetworkPolicyGVK, r.names.Ingress, map[string]any{
		"endpointSelector": r.endpointSelector(),
		"ingress": []any{
			map[string]any{
				"fromEntities": []any{"world"},
				"toPorts":      []any{map[string]any{"ports": []any{port(portIKE, "UDP"), port(portNATT, "UDP")}}},
			},
			map[string]any{
				"fromEndpoints": []any{map[string]any{"matchLabels": from}},
				"toPorts":       []any{map[string]any{"ports": []any{port(r.in.Plan.ManagementPort, "TCP")}}},
			},
		},
	})
}

func anyMap(m map[string]string) map[string]any {
	out := make(map[string]any, len(m)+2)
	for k, v := range m {
		out[k] = v
	}
	return out
}
